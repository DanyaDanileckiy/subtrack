// Extracts only the needed Simple Icons (CC0) into a small offline module. Run: node scripts/gen-logos.mjs
import * as si from 'simple-icons';
import { writeFileSync } from 'node:fs';
import { PRESETS } from '../src/lib/presets.js';
const bySlug = Object.fromEntries(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = {}; const missing = [];
for (const p of PRESETS) { if (!p.slug) continue; const i = bySlug[p.slug]; if (i) out[p.slug] = { t: i.title, h: i.hex, p: i.path }; else missing.push(p.slug); }
writeFileSync(new URL('../src/lib/logos.generated.js', import.meta.url),
  `// AUTO-GENERATED by scripts/gen-logos.mjs from simple-icons (CC0 1.0). Do not edit.\nexport const LOGOS = ${JSON.stringify(out)};\n`);
console.log('presets', PRESETS.length, 'logos', Object.keys(out).length, 'fallback', PRESETS.length - Object.keys(out).length, 'missing slugs', missing);
