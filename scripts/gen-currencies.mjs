// Snapshots every currency from the free, keyless open.er-api.com into an offline fallback table.
// Run: node scripts/gen-currencies.mjs   (needs network; the result is committed)
import { writeFileSync } from 'node:fs';
const j = await (await fetch('https://open.er-api.com/v6/latest/USD')).json();
if (j.result !== 'success') throw new Error('rates fetch failed');
const rates = Object.fromEntries(Object.entries(j.rates).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => [k, Number(v.toPrecision(6))]));
writeFileSync(new URL('../src/lib/currencies.generated.js', import.meta.url),
  `// AUTO-GENERATED by scripts/gen-currencies.mjs. Approximate offline fallback (units per 1 USD).\n// Snapshot: ${j.time_last_update_utc}. Source: https://www.exchangerate-api.com (open access endpoint).\n` +
  `export const SNAPSHOT_DATE = ${JSON.stringify(new Date(j.time_last_update_unix * 1000).toISOString().slice(0, 10))};\nexport const SNAPSHOT_RATES = ${JSON.stringify(rates)};\n`);
console.log('currencies', Object.keys(rates).length);
